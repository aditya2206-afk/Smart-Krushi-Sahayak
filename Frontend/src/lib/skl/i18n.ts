export const TRANSLATIONS: Record<Lang, Dict> = { en, mr, hi };

/** Collapse whitespace so multi-line JSX text matches the dictionary key. */
function normalize(value: string) {
  return value.replace(/\s+/g, " ").trim();
}

let activeLang: Lang = "en";

export function setActiveLang(lang: Lang) {
  activeLang = lang;
}

export function getActiveLang(): Lang {
  return activeLang;
}

export function translate(lang: Lang, value: string) {
  if (typeof value !== "string") return value;
  const key = normalize(value);
  if (!key) return value;
  const hit = TRANSLATIONS[lang][key] ?? (lang === "en" ? undefined : en[key]);
  if (!hit) return value;
  // preserve any leading / trailing whitespace of the original JSX text node
  const lead = value.match(/^\s*/)?.[0] ?? "";
  const tail = value.match(/\s*$/)?.[0] ?? "";
  return lead + hit + tail;
}

/**
 * Global translation helper. Reads the language set by the store, so every
 * component can simply call t("Some text") without extra wiring.
 */
export function t<T>(value: T): T {
  return translate(activeLang, value as unknown as string) as unknown as T;
}

